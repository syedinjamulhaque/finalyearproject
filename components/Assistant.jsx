function MessageInput({ value, onChange, onSend, disabled }) {
  const textareaRef = useRef(null);

  useEffect(() => {
    const el = textareaRef.current;
    if (!el) return;
    el.style.height = "auto";
    el.style.height = Math.min(el.scrollHeight, 160) + "px";
  }, [value]);

  function handleKeyDown(e) {
    if (e.key === "Enter" && !e.shiftKey) {
      e.preventDefault();
      onSend();
    }
  }

  return (
    <div className="border-t border-slate-800/80 px-4 py-3 sm:px-6">
      <div className="flex items-end gap-2 rounded-2xl border border-slate-800 bg-slate-900/70 px-3 py-2 focus-within:border-cyan-500/50">
        <button type="button" className="grid h-8 w-8 shrink-0 place-items-center rounded-lg text-slate-500 hover:text-slate-300">
          <Paperclip className="h-4 w-4" />
        </button>
        <textarea
          ref={textareaRef}
          rows={1}
          value={value}
          onChange={(e) => onChange(e.target.value)}
          onKeyDown={handleKeyDown}
          placeholder="Describe your emergency or ask me anything..."
          className="max-h-40 flex-1 resize-none bg-transparent py-1.5 text-sm text-slate-200 placeholder:text-slate-600 focus:outline-none"
        />
        <button type="button" className="grid h-8 w-8 shrink-0 place-items-center rounded-lg text-slate-500 hover:text-slate-300">
          <Mic className="h-4 w-4" />
        </button>
        <button
          type="button"
          onClick={onSend}
          disabled={disabled}
          className="grid h-8 w-8 shrink-0 place-items-center rounded-lg bg-cyan-500 text-slate-950 transition-opacity hover:bg-cyan-400 disabled:cursor-not-allowed disabled:opacity-30"
        >
          <Send className="h-4 w-4" />
        </button>
      </div>
      <p className="mt-1.5 text-center text-[10px] text-slate-600">
        Enter to send · Shift + Enter for a new line
      </p>
    </div>
  );
}

