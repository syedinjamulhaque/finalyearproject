export default function AIEmergencyAssistant() {
  const [sidebarCollapsed, setSidebarCollapsed] = useState(false);
  const [rightOpen, setRightOpen] = useState(true);
  const [messages, setMessages] = useState([]);
  const [input, setInput] = useState("");
  const [typing, setTyping] = useState(false);
  const scrollRef = useRef(null);

  useEffect(() => {
    scrollRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [messages, typing]);

  function sendMessage(text) {
    const trimmed = (text ?? input).trim();
    if (!trimmed) return;

    const userMsg = { id: crypto.randomUUID(), role: "user", text: trimmed, time: "Just now" };
    setMessages((m) => [...m, userMsg]);
    setInput("");
    setTyping(true);

    setTimeout(() => {
      setTyping(false);
      const attachIncident = /nearby|incident|flood|fire|accident/i.test(trimmed)
        ? NEARBY_INCIDENTS[0]
        : null;
      setMessages((m) => [
        ...m,
        {
          id: crypto.randomUUID(),
          role: "assistant",
          text: MOCK_REPLY_TEXT,
          time: "Just now",
          incident: attachIncident,
        },
      ]);
    }, 1100);
  }

  function handleQuickAction(action) {
    if (action.id === "safety") {
      sendMessage("What safety precautions should I take?");
    } else {
      sendMessage(`(Demo) Navigating to: ${action.label}`);
    }
  }

  function handleNewChat() {
    setMessages([]);
    setInput("");
  }

  return (
    <div className="flex h-screen w-full bg-slate-950 text-slate-200" style={{ fontFamily: "Inter, ui-sans-serif, system-ui" }}>
      <AssistantSidebar
        collapsed={sidebarCollapsed}
        onToggle={() => setSidebarCollapsed((v) => !v)}
        onNewChat={handleNewChat}
      />

      <div className="flex min-w-0 flex-1 flex-col">
        <ChatHeader
          collapsed={sidebarCollapsed}
          onToggle={() => setSidebarCollapsed((v) => !v)}
          rightOpen={rightOpen}
          onToggleRight={() => setRightOpen((v) => !v)}
        />

        <div className="flex-1 overflow-y-auto">
          {messages.length === 0 ? (
            <WelcomeScreen onPick={(p) => sendMessage(p)} />
          ) : (
            <div className="mx-auto flex max-w-2xl flex-col gap-5 px-4 py-6 sm:px-6">
              {messages.map((m) => (
                <ChatMessage key={m.id} role={m.role} text={m.text} time={m.time} incident={m.incident} />
              ))}
              {typing && (
                <div className="flex items-start gap-2.5">
                  <span className="grid h-7 w-7 shrink-0 place-items-center rounded-full bg-slate-800">
                    <Sparkles className="h-3.5 w-3.5 text-cyan-400" />
                  </span>
                  <TypingIndicator />
                </div>
              )}
              <div ref={scrollRef} />
            </div>
          )}
        </div>

        <QuickActions onAction={handleQuickAction} />
        <MessageInput value={input} onChange={setInput} onSend={() => sendMessage()} disabled={!input.trim()} />
      </div>

      <InfoPanel open={rightOpen} onClose={() => setRightOpen(false)} />
    </div>
  );
}
